#!/usr/bin/env python3
"""Generate vp9_tables.h (VP9 default probabilities) from libvpx sources.

usage: gen_vp9_tables.py <libvpx root> <output>  (e.g. external/libvpx nvdec/vp9_tables.h)
The initializers are copied verbatim; only the declarations are rewritten.
"""
import re
import sys

root, out = sys.argv[1], sys.argv[2]


def initializer(path, name):
    src = open(f"{root}/{path}").read()
    m = re.search(r"\b" + re.escape(name) + r"\b[^=;]*=\s*{", src)
    if not m:
        sys.exit(f"{name} not found in {path}")
    i, depth = m.end() - 1, 0
    for j in range(i, len(src)):
        depth += src[j] == "{"
        depth -= src[j] == "}"
        if depth == 0:
            return src[i:j + 1]
    sys.exit(f"unterminated {name}")


TABLES = [
    # (source, libvpx name, our name, declarator)
    ("vp9/common/vp9_entropy.c", "default_coef_probs_4x4", "vp9_default_coef_4x4", "[2][2][6][6][3]"),
    ("vp9/common/vp9_entropy.c", "default_coef_probs_8x8", "vp9_default_coef_8x8", "[2][2][6][6][3]"),
    ("vp9/common/vp9_entropy.c", "default_coef_probs_16x16", "vp9_default_coef_16x16", "[2][2][6][6][3]"),
    ("vp9/common/vp9_entropy.c", "default_coef_probs_32x32", "vp9_default_coef_32x32", "[2][2][6][6][3]"),
    ("vp9/common/vp9_entropymode.c", "vp9_kf_y_mode_prob", "vp9_kf_y_mode_prob", "[10][10][9]"),
    ("vp9/common/vp9_entropymode.c", "vp9_kf_uv_mode_prob", "vp9_kf_uv_mode_prob", "[10][9]"),
    ("vp9/common/vp9_entropymode.c", "default_if_y_probs", "vp9_default_y_mode_prob", "[4][9]"),
    ("vp9/common/vp9_entropymode.c", "default_if_uv_probs", "vp9_default_uv_mode_prob", "[10][9]"),
    ("vp9/common/vp9_entropymode.c", "vp9_kf_partition_probs", "vp9_kf_partition_prob", "[16][3]"),
    ("vp9/common/vp9_entropymode.c", "default_partition_probs", "vp9_default_partition_prob", "[16][3]"),
    ("vp9/common/vp9_entropymode.c", "default_inter_mode_probs", "vp9_default_inter_mode_prob", "[7][3]"),
    ("vp9/common/vp9_entropymode.c", "default_intra_inter_p", "vp9_default_intra_inter_prob", "[4]"),
    ("vp9/common/vp9_entropymode.c", "default_comp_inter_p", "vp9_default_comp_inter_prob", "[5]"),
    ("vp9/common/vp9_entropymode.c", "default_comp_ref_p", "vp9_default_comp_ref_prob", "[5]"),
    ("vp9/common/vp9_entropymode.c", "default_single_ref_p", "vp9_default_single_ref_prob", "[5][2]"),
    ("vp9/common/vp9_entropymode.c", "default_skip_probs", "vp9_default_skip_prob", "[3]"),
    ("vp9/common/vp9_entropymode.c", "default_switchable_interp_prob", "vp9_default_interp_prob", "[4][2]"),
]

STRUCTS = [
    # struct tx_probs { p8x8[2][1]; p16x16[2][2]; p32x32[2][3]; }
    ("vp9/common/vp9_entropymode.c", "default_tx_probs", "struct vp9_tx_probs vp9_default_tx_probs"),
    # nmv_context { joints[3]; comps[2] { sign; classes[10]; class0[1]; bits[10];
    #               class0_fp[2][3]; fp[3]; class0_hp; hp; } }
    ("vp9/common/vp9_entropymv.c", "default_nmv_context", "struct vp9_mv_probs vp9_default_mv_probs"),
]

with open(out, "w") as f:
    f.write("/*\n * VP9 default probabilities, generated by gen_vp9_tables.py from libvpx\n"
            " * vp9/common/vp9_entropy.c, vp9_entropymode.c and vp9_entropymv.c.\n *\n")
    for line in open(f"{root}/LICENSE").read().strip().splitlines():
        f.write((" * " + line).rstrip() + "\n")
    f.write(" */\n#pragma once\n\n#include <stdint.h>\n\n#include \"vp9_types.h\"\n\n")
    for path, name, ours, decl in TABLES:
        f.write(f"static const uint8_t {ours}{decl} = {initializer(path, name)};\n\n")
    for path, name, ours in STRUCTS:
        f.write(f"static const {ours} = {initializer(path, name)};\n\n")
